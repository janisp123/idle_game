import assert from "node:assert/strict";
import {newGame,chooseActivity,enterGame,enterGameWithApprentice,xpToNextLevel,DAY_MS} from "../site/play/engine.mjs";
import {loginReport} from "../site/play/login-report.mjs";
import {awardAttributeTime} from "../site/play/attributes.mjs";
const rng=()=>.5;
let before=newGame(0);before.skills.fighting.level=11;before.coins=1000;
before=chooseActivity(before,"fighting",0,rng).state;
const actual=enterGameWithApprentice(before,DAY_MS,rng),model=loginReport(before,actual);
assert.equal(model.arena.bouts,actual.offlineArena.bouts);
assert.equal(model.arena.losses,actual.offlineArena.defeats+actual.offlineArena.doubleDeaths);
assert.equal(model.arena.bouts,model.arena.victories+model.arena.losses);
assert.equal(model.wallet.earned,actual.offlineArena.coins);
assert.equal(model.wallet.before+model.wallet.earned-model.wallet.spent,model.wallet.after);
assert.equal(model.upgradeCount,actual.autoEquipment.upgrades.length);
assert.equal(model.upgrades.reduce((n,x)=>n+x.cost,0),model.wallet.spent);
assert.equal(model.elapsedMs,DAY_MS);
assert.ok(model.expertise.length>0);
assert.ok(model.attributes.some(x=>x.xp>0));
assert.equal(model.stage,before.autoFight.stage);
const failed=loginReport(before,enterGame(before,DAY_MS,rng),{saved:false,automationUnavailable:true});
assert.equal(failed.upgradeCount,0);assert.equal(failed.wallet.spent,0);assert.equal(failed.saved,false);
let master=newGame(0);master.skills.fishing.level=51;master.skills.mining.xp=xpToNextLevel(1);master.items.stone=12;master.apprenticeMasterConsent=1;
const mastered=enterGameWithApprentice(master,0,rng),m=loginReport(master,mastered);
assert.equal(m.levels,1);assert.equal(m.tribute.stone,12);assert.deepEqual(m.skills.find(x=>x.id==="mining"),{id:"mining",completed:0,xp:0,from:1,to:2,ready:false});
const mixed=newGame(0);const after={...mixed,settledAtMs:3600000,coins:24,attributeEffort:awardAttributeTime(mixed.attributeEffort,"mining",3600000)};
after.attributeEffortActive={...after.attributeEffort};
const reports=[{activity:"mining",completed:2,gainedXP:4,items:{stone:3,iron_ore:2}},{activity:"smithing",completed:1,gainedXP:3,items:{iron_ingot:1},consumed:{iron_ore:2}},{activity:"fighting",completed:3,gainedXP:5,arena:{bouts:4,victories:2,defeats:1,doubleDeaths:1,downtimeMs:40000,coins:24}}];
const synthetic=loginReport(mixed,{state:after,reports,report:reports[2]});
assert.equal(synthetic.arena.bouts,4);assert.equal(synthetic.arena.winRate,.5);assert.equal(synthetic.arena.losses,2);
assert.deepEqual(synthetic.gained,{stone:3,iron_ore:2,iron_ingot:1});assert.deepEqual(synthetic.consumed,{iron_ore:2});assert.equal(synthetic.skills.length,3);
assert.equal(synthetic.attributes.reduce((n,x)=>n+x.xp,0),100);
const zero=loginReport(mixed,enterGame(mixed,0,rng));assert.equal(zero.arena.winRate,null);assert.equal(zero.upgradeCount,0);
console.log("A5 report projection: 26 assertions passed");
