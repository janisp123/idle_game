import assert from "node:assert/strict";
import {newTeamGame,newGame,teamFromState,readSave,chooseActivity,settle,settleLive,enterGame,enterGameWithApprentice,setTeamWeapon,buyTeamEquipment,autoEquipmentPreview,activityRewardCapped,desiredArenaTeam} from "../site/play/engine.mjs";
import {startTeamSession,settleTeamSession} from "../site/play/team-timeline.mjs";
import {awardTeamPractice} from "../site/play/team.mjs";
import {BOUT_MS} from "../site/play/combat.mjs";
import {finishAutoFightBout} from "../site/play/auto-fight.mjs";
const seed=20261126,random=()=>.5,now=seed;
const fresh=newTeamGame(now);
assert.deepEqual(readSave(JSON.stringify(fresh)),fresh);
assert.equal(readSave({...fresh,teamwork:{level:1,xp:101}}),null);
assert.equal(readSave({...fresh,teamSecond:null}),null);
assert.equal(readSave(newGame(now)).teamSecond,undefined);
let state=chooseActivity(fresh,"fighting",now,random).state;
state={...state,skills:{...state.skills,fighting:{level:100,xp:0}}};
const frozen=startTeamSession(desiredArenaTeam(state),1,now>>>0);
const expected=settleTeamSession(frozen,2*BOUT_MS);
const result=settle(state,now+2*BOUT_MS,random);
assert.equal(result.state.coins,expected.coins);
assert.equal(result.state.teamwork.xp,2);
assert.deepEqual(result.state.combatSession,expected.session);
assert.deepEqual(teamFromState(result.state),awardTeamPractice(teamFromState(state),frozen.players,expected.practiceMs));
assert.deepEqual(result.state.autoFight,state.autoFight,"offline difficulty frozen");
assert.deepEqual(readSave(JSON.stringify(result.state)),result.state);
assert.equal(settle(result.state,result.state.settledAtMs,random).state.coins,result.state.coins);
const partial=settle(state,now+1000,random).state;
const changed=setTeamWeapon(partial,"second","hammer",partial.settledAtMs,random).state;
assert.equal(changed.teamSecond.combatLoadout,"hammer");
assert.equal(changed.combatSession.players.second.loadout,frozen.players.second.loadout);
const completed=settle(changed,now+BOUT_MS,random).state;
assert.equal(completed.combatSession.players.second.loadout,"hammer");
assert.equal(completed.teamSecond.expertise.hammer,0);
assert.ok(completed.teamSecond.expertise.bow>0);
const ready={...partial,teamwork:{level:1,xp:100},coins:0};
assert.equal(enterGame(ready,ready.settledAtMs,random).state.teamwork.level,1);
const login=enterGameWithApprentice(ready,ready.settledAtMs,random);
assert.equal(login.state.teamwork.level,2);
assert.equal(login.teamworkLevelGained,1);
assert.equal(login.state.combatSession.teamworkLevel,1);
assert.ok(readSave(login.state));
const after=settle(login.state,now+BOUT_MS,random).state;
assert.equal(after.combatSession.teamworkLevel,2);
assert.equal(after.teamwork.xp,1);
const beforeBoundary=settle(state,now+BOUT_MS-1000,random).state;
const live=settleLive(beforeBoundary,now+BOUT_MS,random).state;
const one=settleTeamSession(frozen,BOUT_MS);
assert.deepEqual(live.autoFight,finishAutoFightBout(state.autoFight,one.victories?"victory":one.defeats?"defeat":"double_death",true));
const funded={...fresh,coins:100000,skills:{...fresh.skills,fighting:{level:11,xp:0}}};
const purchase=buyTeamEquipment(funded,"second","head:plate",{grade:0,quality:"poor"},now,random);
assert.ok(purchase.purchased);
assert.equal(purchase.state.teamSecond.armour.head,"plate");
assert.equal(purchase.state.armour.head,"none");
assert.ok(purchase.state.coins<funded.coins);
const upgrades=enterGameWithApprentice(purchase.state,now,random);
assert.ok(upgrades.autoEquipment.upgrades.some(u=>u.fighterId==="first"));
assert.ok(upgrades.autoEquipment.upgrades.some(u=>u.fighterId==="second"));
assert.equal(purchase.state.coins-upgrades.state.coins,upgrades.autoEquipment.spent);
assert.equal(autoEquipmentPreview(upgrades.state).next?.available??false,false);
assert.deepEqual(readSave(upgrades.state),upgrades.state);
const cap=settle(chooseActivity(fresh,"fighting",now,random).state,now+20*365*86400000,random).state;
assert.ok(activityRewardCapped(cap));
const later=settle(cap,cap.settledAtMs+86400000,random).state;
assert.equal(later.coins,cap.coins);
assert.deepEqual(later.teamwork,cap.teamwork);
assert.deepEqual(teamFromState(later),teamFromState(cap));
console.log(JSON.stringify({teamEngine:"PASS",offlineBouts:expected.bouts,coins:expected.coins,practice:expected.practiceMs,upgrades:upgrades.autoEquipment.upgrades.length,spent:upgrades.autoEquipment.spent,capTeamwork:cap.teamwork,liveStage:live.autoFight.stage}));
